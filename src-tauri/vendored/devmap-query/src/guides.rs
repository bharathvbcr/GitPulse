//! The agent workspace guide: `AGENTS.md` / `CLAUDE.md`, written from the map.
//!
//! A map nothing points an agent at is a map nothing reads. The guide is the
//! pointer — it names the artifact, says which fields to trust, and names the
//! commands that answer questions the artifact cannot.
//!
//! Ported from `src/devcouncil/indexing/map_artifacts.py`, minus the parts that
//! were about the orchestrator rather than the index: the DevCouncil task loop,
//! the wiki index, and `dev map` as the command name. What is kept, deliberately,
//! is the part that makes the guide honest.
//!
//! # Why the text is computed rather than templated
//!
//! Steps 5 and 6 change depending on what the map in hand actually carries.
//!
//! The kernel emitted `"role_files": {}` and `"handoff_paths": []` as literals
//! for the whole life of both fields, while the guide told every agent to use
//! them. An instruction is a claim about the artifact, and that claim was false:
//! an agent that followed step 5 got an empty mapping back and read the
//! emptiness as *this subsystem has no roles* rather than as *the producer
//! declined to answer*. Four readers took it at its word.
//!
//! So the guide states which of the two it is. A field the producer did not
//! compute is described as not computed, with what to use instead. This is the
//! same rule the rest of the kernel follows for budgets and truncation: a check
//! that could not run must never read like a check that ran and passed.

use serde_json::Value;
use std::path::{Path, PathBuf};

/// The marker that says a guide is ours to rewrite.
///
/// A file without it is left completely alone: `CLAUDE.md` is far more often a
/// hand-written file than a generated one, and silently replacing somebody's
/// notes with a generated index is not a trade any refresh should make.
pub const AGENT_GUIDE_MARKER: &str =
    "<!-- Managed by devmap: keep this file in sync with the repo map. -->";

/// The marker DevCouncil's own writer used.
///
/// Recognised so a repository whose guide was generated by `dev map` keeps
/// being updated after the split, instead of being treated as hand-written and
/// left to go stale beside a map that moved. Only ever *read* — a guide this
/// module writes carries [`AGENT_GUIDE_MARKER`].
pub const LEGACY_AGENT_GUIDE_MARKER: &str =
    "<!-- Managed by dev map: keep this file in sync with .devcouncil/repo_map.json. -->";

/// The line that opens the one block DevMap owns inside a hand-written guide.
///
/// A whole-file marker makes the entire guide ours; a person who wants their
/// own notes in `CLAUDE.md` *and* a current DevMap section puts these two lines
/// where the section should go (or runs with `--adopt-guides` once, which
/// appends them). Everything outside the pair is theirs and is kept byte for
/// byte. Matched as a whole line, outside fenced code, so a guide that merely
/// quotes the marker in an example is not taken over.
pub const AGENT_GUIDE_BLOCK_BEGIN: &str =
    "<!-- devmap:begin (generated by devmap; edit outside the devmap:begin/devmap:end lines) -->";

/// The line that closes the block [`AGENT_GUIDE_BLOCK_BEGIN`] opens.
pub const AGENT_GUIDE_BLOCK_END: &str = "<!-- devmap:end -->";

/// What to do with a guide that exists and carries no marker of any kind.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum HandWrittenGuides {
    /// Leave it alone. The default, and the only behaviour before blocks
    /// existed: silently changing somebody's notes is not a trade any refresh
    /// should make unasked.
    Preserve,
    /// Append a DevMap block after the existing text, which is kept byte for
    /// byte. Asked for explicitly (`--adopt-guides`); once the block exists,
    /// later refreshes rewrite only the block and need no flag.
    Adopt,
}

/// Whether a guide run only computes what it would do, or does it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GuidePass {
    /// Inspect every destination and report the outcome; write nothing and
    /// acquire no write access. `integrate --dry-run` / `--check`.
    Plan,
    /// Inspect the whole set, then write.
    Write,
}

