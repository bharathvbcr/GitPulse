/// Which part of an existing guide is ours.
enum Ownership<'a> {
    /// The file carries a whole-file marker: all of it is ours.
    WholeFile,
    /// Bytes `start..end` are the block, from the start of the begin line to
    /// the end of the end line; `terminator` is the end line's own line ending,
    /// kept so a refresh of an unchanged block is byte-identical.
    Block {
        start: usize,
        end: usize,
        terminator: &'a str,
    },
    /// No marker of any kind. `ends_in_code` is true when the file ends inside
    /// a code fence it never closes, where an appended block would be code.
    HandWritten { ends_in_code: bool },
    /// Block marker lines that do not delimit exactly one block.
    Malformed(String),
}

/// An open code fence: its character and how many of them opened it.
struct Fence {
    marker: char,
    len: usize,
}

/// Columns of leading indentation (a tab advances to the next multiple of
/// four, as CommonMark counts it) and the rest of the line.
fn indentation(line: &str) -> (usize, &str) {
    let mut cols = 0;
    for (i, c) in line.char_indices() {
        match c {
            ' ' => cols += 1,
            '\t' => cols += 4 - cols % 4,
            _ => return (cols, &line[i..]),
        }
    }
    (cols, "")
}

/// The fence a line opens, if it opens one: at most three columns of indent,
/// then three or more backticks or tildes; a backtick fence's info string may
/// not hold a backtick.
fn fence_opening(line: &str) -> Option<Fence> {
    let (cols, rest) = indentation(line);
    if cols > 3 {
        return None;
    }
    let marker = rest.chars().next().filter(|c| *c == '`' || *c == '~')?;
    let len = rest.chars().take_while(|c| *c == marker).count();
    if len < 3 || (marker == '`' && rest[len..].contains('`')) {
        return None;
    }
    Some(Fence { marker, len })
}

/// Whether a line closes `fence`: at most three columns of indent, at least as
/// many of the same character, and nothing after them but whitespace.
fn closes(line: &str, fence: &Fence) -> bool {
    let (cols, rest) = indentation(line);
    let len = rest.chars().take_while(|c| *c == fence.marker).count();
    cols <= 3 && len >= fence.len && rest[len * fence.marker.len_utf8()..].trim().is_empty()
}

/// The closing token of the raw HTML block a line opens, if it opens one that
/// it does not also close: a comment (`<!--` without its `-->`), or a `pre`,
/// `script`, `style` or `textarea` element (CommonMark's first two kinds of
/// HTML block, which run to their closing token). Text inside one is not
/// prose, so a marker quoted there is not a marker.
fn html_block_opening(line: &str) -> Option<&'static str> {
    let (cols, rest) = indentation(line);
    if cols > 3 {
        return None;
    }
    let lower = rest.to_ascii_lowercase();
    if let Some(after) = lower.strip_prefix("<!--") {
        // `<!-->` and `<!--->` are complete (empty) comments in CommonMark.
        if after.starts_with('>') || after.starts_with("->") {
            return None;
        }
        return (!after.contains("-->")).then_some("-->");
    }
    for (tag, close) in [
        ("<pre", "</pre>"),
        ("<script", "</script>"),
        ("<style", "</style>"),
        ("<textarea", "</textarea>"),
    ] {
        if let Some(after) = lower.strip_prefix(tag) {
            let boundary = after
                .chars()
                .next()
                .is_none_or(|c| c == '>' || c.is_whitespace());
            if boundary {
                return (!after.contains(close)).then_some(close);
            }
        }
    }
    None
}

/// Whether a line, outside code, is exactly `marker`: at most three columns
/// of indent (four is an indented code block) and nothing else but trailing
/// whitespace.
fn is_marker_line(line: &str, marker: &str) -> bool {
    // A byte-order mark an editor left at the head of the file is not text.
    let (cols, rest) = indentation(line.strip_prefix('\u{feff}').unwrap_or(line));
    cols <= 3 && rest.trim_end() == marker
}

/// Find the marker lines in `existing` that are not code.
///
/// Code follows CommonMark closely enough that a guide quoting the markers in
/// an example is never taken over: a fenced block runs from an opening fence
/// to a closing one of the same character and at least the same length (so a
/// four-backtick fence can quote a three-backtick example), or to the end of
/// the file when it is never closed; a line indented four columns or more is
/// never a marker. The whole-file marker counts only on such a line too — a
/// guide that quotes it inside a fence is not thereby wholly ours.
///
/// Block markers win over the whole-file marker: a file that has both is a
/// hand-written file with a block in it (the block body never carries the
/// whole-file marker, so only a person put it there), and the narrower claim
/// is the one that cannot delete their text.
fn ownership(existing: &str) -> Ownership<'_> {
    let mut begins = Vec::new();
    let mut ends = Vec::new();
    let mut whole_file_marked = false;
    let mut fence: Option<Fence> = None;
    let mut html: Option<&'static str> = None;
    let mut offset = 0;
    for line in existing.split_inclusive('\n') {
        let start = offset;
        offset += line.len();
        let bare = line.trim_end_matches(['\n', '\r']);
        if let Some(open) = &fence {
            if closes(bare, open) {
                fence = None;
            }
            continue;
        }
        if let Some(close) = html {
            if bare.to_ascii_lowercase().contains(close) {
                html = None;
            }
            continue;
        }
        if let Some(open) = fence_opening(bare) {
            fence = Some(open);
            continue;
        }
        if let Some(close) = html_block_opening(bare) {
            html = Some(close);
            continue;
        }
        if is_marker_line(bare, AGENT_GUIDE_BLOCK_BEGIN) {
            // A byte-order mark before the begin line belongs to the file, not
            // the block, and is kept.
            begins.push(start + if bare.starts_with('\u{feff}') { 3 } else { 0 });
        } else if is_marker_line(bare, AGENT_GUIDE_BLOCK_END) {
            ends.push((start, offset, &line[bare.len()..]));
        } else if is_marker_line(bare, AGENT_GUIDE_MARKER)
            || is_marker_line(bare, LEGACY_AGENT_GUIDE_MARKER)
        {
            whole_file_marked = true;
        }
    }
    match (begins.as_slice(), ends.as_slice()) {
        ([], []) if whole_file_marked => Ownership::WholeFile,
        ([], []) => Ownership::HandWritten {
            ends_in_code: fence.is_some() || html.is_some(),
        },
        ([begin], [(end_start, end, terminator)]) if begin < end_start => Ownership::Block {
            start: *begin,
            end: *end,
            terminator,
        },
        ([begin], [(end_start, _, _)]) if begin > end_start => Ownership::Malformed(
            "the devmap:end line comes before the devmap:begin line".to_string(),
        ),
        _ => Ownership::Malformed(format!(
            "{} devmap:begin and {} devmap:end line(s); expected exactly one of each, \
             begin first",
            begins.len(),
            ends.len()
        )),
    }
}

/// The block lines around `body`, ending with `terminator`.
fn block_text(body: &str, terminator: &str) -> String {
    format!("{AGENT_GUIDE_BLOCK_BEGIN}\n{body}\n{AGENT_GUIDE_BLOCK_END}{terminator}")
}

/// What should happen to one existing destination.
struct Decision {
    disposition: GuideDisposition,
    /// The new contents, when the file is to be written.
    content: Option<String>,
    block: bool,
}

impl Decision {
    fn compare(existing: &str, content: String, block: bool) -> Self {
        if existing == content {
            Self {
                disposition: GuideDisposition::Unchanged,
                content: None,
                block,
            }
        } else {
            Self {
                disposition: GuideDisposition::Updated,
                content: Some(content),
                block,
            }
        }
    }

    fn leave(disposition: GuideDisposition, block: bool) -> Self {
        Self {
            disposition,
            content: None,
            block,
        }
    }
}

/// Decide what to do with an existing `AGENTS.md` / `CLAUDE.md`.
///
/// `whole` is the complete generated file (marker included), `body` what a
/// block holds.
fn decide_guide(
    existing: &str,
    whole: &str,
    body: &str,
    hand_written: HandWrittenGuides,
) -> Decision {
    match ownership(existing) {
        Ownership::Malformed(reason) => {
            Decision::leave(GuideDisposition::MalformedBlock(reason), true)
        }
        Ownership::Block {
            start,
            end,
            terminator,
        } => {
            let content = format!(
                "{}{}{}",
                &existing[..start],
                block_text(body, terminator),
                &existing[end..]
            );
            Decision::compare(existing, content, true)
        }
        Ownership::WholeFile => Decision::compare(existing, whole.to_string(), false),
        Ownership::HandWritten { ends_in_code } => match hand_written {
            HandWrittenGuides::Preserve => Decision::leave(GuideDisposition::NotOurs, false),
            // Appended after an unclosed fence, the block would be code: not
            // found by the next run, which would append another.
            HandWrittenGuides::Adopt if ends_in_code => Decision::leave(
                GuideDisposition::MalformedBlock(
                    "the file ends inside a code fence or HTML block it never closes, so a block appended \
                     there would be code; close the fence or add the devmap:begin/devmap:end \
                     lines yourself"
                        .to_string(),
                ),
                false,
            ),
            HandWrittenGuides::Adopt => {
                let separator = if existing.is_empty() {
                    ""
                } else if existing.ends_with('\n') {
                    "\n"
                } else {
                    "\n\n"
                };
                Decision {
                    disposition: GuideDisposition::Adopted,
                    content: Some(format!("{existing}{separator}{}", block_text(body, "\n"))),
                    block: true,
                }
            }
        },
    }
}

enum Step {
    /// Nothing to write (unchanged, not ours, malformed, or a plan-only pass).
    Leave,
    /// Create the file with this text.
    Create(String),
    /// Replace the file's contents. The writer is present only in a
    /// [`GuidePass::Write`] pass, acquired while the inspection still names
    /// this exact file.
    Rewrite(String, Option<Box<devmap_extract::safe_fs::SafeFile>>),
}

struct Prepared {
    path: PathBuf,
    disposition: GuideDisposition,
    block: bool,
    step: Step,
}

/// The sibling guide `path` is a symlink to, when it is exactly that: a link
/// in the same directory whose target is a bare name of another guide in
/// [`GUIDE_FILENAMES`] that exists as a regular file there. `CLAUDE.md ->
/// AGENTS.md` is the common case; the sibling is handled as itself, and the
/// link is never written through. Any other symlink is not this, and the
/// destination checks refuse it as before.
fn linked_sibling(repo_root: &Path, path: &Path) -> Option<String> {
    if !std::fs::symlink_metadata(path)
        .ok()?
        .file_type()
        .is_symlink()
    {
        return None;
    }
    let target = std::fs::read_link(path).ok()?;
    let name = target.to_str()?;
    let name = name.strip_prefix("./").unwrap_or(name);
    let own = path.file_name()?.to_str()?;
    if name == own || !GUIDE_FILENAMES.contains(&name) {
        return None;
    }
    let meta = std::fs::symlink_metadata(repo_root.join(name)).ok()?;
    meta.file_type().is_file().then(|| name.to_string())
}

/// Inspect one destination. A plan pass that cannot read it — a symlink, a file
/// over the read limit, no permission — reports it as
/// [`GuideDisposition::Refused`] rather than failing the whole plan: a
/// `--check` must say which file needs a person, and a write would refuse the
/// same file. A write pass still fails, before anything is written.
fn prepare_destination(
    path: PathBuf,
    pass: GuidePass,
    create: &str,
    decide: impl FnOnce(&str) -> Decision,
) -> std::io::Result<Prepared> {
    match (
        inspect_destination(path.clone(), pass, create, decide),
        pass,
    ) {
        (Err(error), GuidePass::Plan) => Ok(Prepared {
            path,
            disposition: GuideDisposition::Refused(error.to_string()),
            block: false,
            step: Step::Leave,
        }),
        (result, _) => result,
    }
}

fn inspect_destination(
    path: PathBuf,
    pass: GuidePass,
    create: &str,
    decide: impl FnOnce(&str) -> Decision,
) -> std::io::Result<Prepared> {
    use devmap_extract::safe_fs::{Access, Creation, SafeFile};
    match SafeFile::open(&path, Access::Read, Creation::Never) {
        Ok(mut file) => {
            let existing = file.read_text(devmap_extract::MAX_SOURCE_BYTES)?;
            let decision = decide(&existing);
            let step = match decision.content {
                None => Step::Leave,
                Some(content) => {
                    let writer = match pass {
                        GuidePass::Plan => None,
                        GuidePass::Write => {
                            file.require_owned()?;
                            let writer = SafeFile::open(&path, Access::ReadWrite, Creation::Never)?;
                            file.check_unchanged()?;
                            Some(Box::new(writer))
                        }
                    };
                    Step::Rewrite(content, writer)
                }
            };
            Ok(Prepared {
                path,
                disposition: decision.disposition,
                block: decision.block,
                step,
            })
        }
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(Prepared {
            path,
            disposition: GuideDisposition::Created,
            block: false,
            step: Step::Create(create.to_string()),
        }),
        Err(error) => Err(error),
    }
}

impl Prepared {
    fn apply(self, pass: GuidePass) -> std::io::Result<GuideOutcome> {
        use devmap_extract::safe_fs::{Access, Creation, SafeFile};
        if pass == GuidePass::Write {
            match self.step {
                Step::Leave => {}
                Step::Create(text) => {
                    SafeFile::open(&self.path, Access::ReadWrite, Creation::New)?
                        .rewrite(text.as_bytes())?;
                }
                Step::Rewrite(text, writer) => {
                    let mut writer = writer.ok_or_else(|| {
                        std::io::Error::other("guide rewrite planned without write access")
                    })?;
                    writer.rewrite(text.as_bytes())?;
                }
            }
        }
        Ok(GuideOutcome {
            path: self.path,
            disposition: self.disposition,
            block: self.block,
        })
    }
}

/// Write the marker-guarded guides and the Cursor always-apply rule under
/// `repo_root`, leaving hand-written guides alone.
///
/// Every file is reported, including the ones left alone, so a caller can say
/// *why* a guide was not refreshed rather than reporting silence as success.
pub fn write_agent_guides(
    repo_root: &Path,
    map: &Value,
    map_rel: &str,
    graph_rel: &str,
    store_rel: &str,
) -> std::io::Result<Vec<GuideOutcome>> {
    agent_guides(
        repo_root,
        map,
        map_rel,
        graph_rel,
        store_rel,
        HandWrittenGuides::Preserve,
        GuidePass::Write,
    )
}

/// Plan or write the guides and the Cursor rule: the one implementation every
/// caller goes through, so a `--check` and a write cannot disagree about what a
/// file's markers mean.
///
/// Ownership, per guide file:
/// - absent: created, wholly ours (whole-file marker);
/// - whole-file marker: rewritten whole;
/// - exactly one `devmap:begin` line followed by one `devmap:end` line
///   (outside fenced code): only the lines between them are rewritten, and
///   every byte outside them is kept;
/// - any other count or order of block lines: left alone and reported as
///   [`GuideDisposition::MalformedBlock`];
/// - no marker: left alone, or with [`HandWrittenGuides::Adopt`], a block is
///   appended after the existing text.
///
/// The Cursor rule is owned by its path and rewritten whole. The entire set is
/// inspected before any destination is created or modified.
pub fn agent_guides(
    repo_root: &Path,
    map: &Value,
    map_rel: &str,
    graph_rel: &str,
    store_rel: &str,
    hand_written: HandWrittenGuides,
    pass: GuidePass,
) -> std::io::Result<Vec<GuideOutcome>> {
    let body = agent_guide_body(map, map_rel, graph_rel, store_rel);
    let whole = format!("{AGENT_GUIDE_MARKER}\n\n{body}\n");
    let rule_text = cursor_rule_text(map_rel);
    let mut prepared = Vec::with_capacity(GUIDE_FILENAMES.len() + 1);
    // Inspect the entire set before creating or modifying any destination.
    // A readable guide that needs no write needs neither write access nor
    // ownership.
    for filename in GUIDE_FILENAMES {
        let path = repo_root.join(filename);
        if let Some(sibling) = linked_sibling(repo_root, &path) {
            prepared.push(Prepared {
                path,
                disposition: GuideDisposition::Linked(sibling),
                block: false,
                step: Step::Leave,
            });
            continue;
        }
        prepared.push(prepare_destination(path, pass, &whole, |existing| {
            decide_guide(existing, &whole, &body, hand_written)
        })?);
    }
    prepared.push(prepare_destination(
        repo_root.join(CURSOR_RULE_REL),
        pass,
        &rule_text,
        |existing| Decision::compare(existing, rule_text.clone(), false),
    )?);
    prepared.into_iter().map(|plan| plan.apply(pass)).collect()
}

