pub const GUIDE_FILENAMES: &[&str] = &["AGENTS.md", "CLAUDE.md"];

/// Cursor always-apply rule emitted beside the guides.
///
/// Owned by path: `devmap.mdc` is DevMap's claim. A hand-written rule that
