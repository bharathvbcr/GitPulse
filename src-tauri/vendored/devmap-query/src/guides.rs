pub const CURSOR_RULE_REL: &str = ".cursor/rules/devmap.mdc";

/// One guide file the writer considered.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GuideOutcome {
    pub path: PathBuf,
    /// What the writer did, and — when it did nothing — why.
    pub disposition: GuideDisposition,
    /// True when DevMap owns only a delimited block of this file rather than
    /// the whole of it.
    pub block: bool,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum GuideDisposition {
    /// The file did not exist and was created.
    Created,
    /// The file carried a marker and its text changed.
    Updated,
    /// The file carried a marker and already held exactly this text.
    ///
    /// Reported rather than folded into `Updated` because the difference is the
    /// whole point of checking: rewriting an identical file churns mtime for
    /// every watcher on the tree, and moves the guide's own entry in the
    /// inventory the freshness stamps were computed over.
    Unchanged,
    /// The file exists and carries no marker: hand-written, left alone.
    NotOurs,
    /// A hand-written guide had a DevMap block appended after its text, because
    /// the caller asked for [`HandWrittenGuides::Adopt`].
    Adopted,
    /// The file carries block marker lines that do not delimit exactly one
    /// block (one begin line, then one end line). Left alone: guessing which
    /// span is ours could delete somebody's text. The reason names what was
    /// found.
    MalformedBlock(String),
    /// A plan pass could not read the file (a symlink, a file over the read
    /// limit, no permission); a write would refuse it too. The reason is the
    /// error.
    Refused(String),
    /// The file is a symlink to the named sibling guide in the same directory
    /// (`CLAUDE.md -> AGENTS.md`). The sibling is handled as itself; nothing is
    /// written through the link, and it needs nobody.
    Linked(String),
}

impl GuideDisposition {
    /// The stable name used in JSON payloads.
    pub fn as_str(&self) -> &'static str {
        match self {
            Self::Created => "created",
            Self::Updated => "updated",
            Self::Unchanged => "unchanged",
            Self::NotOurs => "not_ours",
            Self::Adopted => "adopted",
            Self::MalformedBlock(_) => "malformed_block",
            Self::Refused(_) => "refused",
            Self::Linked(_) => "linked",
        }
    }

    /// Why the file was left alone, when that needs a person.
    pub fn reason(&self) -> Option<&str> {
        match self {
            Self::MalformedBlock(reason) | Self::Refused(reason) => Some(reason),
            _ => None,
        }
    }
}

impl GuideOutcome {
    /// Whether this outcome changed the working tree.
    ///
    /// The caller needs this, not a count: a guide this run created or rewrote
    /// is a file in the tree, and unless the repository ignores it, it is part
    /// of the inventory the freshness stamps were computed over. A caller that
    /// changed the tree after stamping must restamp, or the map it just wrote
    /// reads stale the instant it lands.
    pub fn changed(&self) -> bool {
        matches!(
            self.disposition,
            GuideDisposition::Created | GuideDisposition::Updated | GuideDisposition::Adopted
        )
    }

    /// Whether a person has to act before this guide can be kept current.
    ///
    /// A hand-written guide is a choice and needs nothing; a malformed block is
    /// a guide that asked to be maintained and cannot be, so a `--check` must
    /// not read it as clean.
    pub fn needs_attention(&self) -> bool {
        matches!(
            self.disposition,
            GuideDisposition::MalformedBlock(_) | GuideDisposition::Refused(_)
        )
    }
}

/// Whether this map carries evidence that subsystem role buckets were computed.
///
/// Two independent positive claims, either of which settles it: the producer's
/// own marker at `meta.devmap_rust.role_files_computed`, and a non-empty
/// `role_files` on any subsystem — a map that names one bucket demonstrably
/// computed them. The second is what answers for a map written before the
/// marker existed.
///
/// Note the asymmetry: both are *positive* claims. Absence proves nothing, and
/// is therefore reported as "not computed" rather than as "no roles".
pub fn role_files_established(map: &Value) -> bool {
    if map
        .pointer("/meta/devmap_rust/role_files_computed")
        .and_then(Value::as_bool)
        == Some(true)
    {
        return true;
    }
    subsystems(map).any(|sub| {
        sub.get("role_files")
            .and_then(Value::as_object)
            .is_some_and(|roles| !roles.is_empty())
    })
}

/// Whether this map carries evidence that cross-subsystem handoff paths were
/// computed. The twin of [`role_files_established`], same two claims.
pub fn handoff_paths_established(map: &Value) -> bool {
    if map
        .pointer("/meta/devmap_rust/handoff_paths_computed")
        .and_then(Value::as_bool)
        == Some(true)
    {
        return true;
    }
    subsystems(map).any(|sub| {
        sub.get("handoff_paths")
            .and_then(Value::as_array)
            .is_some_and(|paths| !paths.is_empty())
    })
}

fn subsystems(map: &Value) -> impl Iterator<Item = &Value> {
    map.get("subsystems")
        .and_then(Value::as_array)
        .map(|items| items.as_slice())
        .unwrap_or(&[])
        .iter()
}

/// Step 5, told against what this map actually holds.
fn role_buckets_step(map: &Value) -> String {
    if role_files_established(map) {
        "5. Use `role_files` in `subsystems` for subsystem role buckets (tests, entry, api, \
models, services, config, docs, other). Each bucket is a capped **sample** for orientation, not \
an inventory — `role_file_counts` carries the real per-role total, and `files` is the complete \
list."
            .to_string()
    } else {
        "5. `role_files` in `subsystems` was NOT computed by the writer that produced this map \
— an empty bucket there is the producer declining to answer, not a subsystem without roles. Use \
`files` (filtered by `area`) instead, and re-run `devmap build --manifest` with a current kernel to get the \
buckets."
            .to_string()
    }
}

/// Step 6, told against what this map actually holds.
fn cross_subsystem_step(map: &Value) -> String {
    if handoff_paths_established(map) {
        "6. Use `neighbors` and `handoff_paths` in `subsystems` to follow cross-subsystem flow. \
`handoff_paths` names the ordered file pairs a subsystem reaches other subsystems through; both \
are capped, and `liveness_meta.subsystems` reports what was cut."
            .to_string()
    } else {
        "6. Use `neighbors` in `subsystems` to follow cross-subsystem flow. `handoff_paths` was \
NOT computed by the writer that produced this map — an empty list there is the producer declining \
to answer, not evidence that nothing crosses. Re-run `devmap build --manifest` with a current kernel to get \
it."
        .to_string()
    }
}

/// Longest a repository-derived name may be in a generated guide.
const MAX_INLINE_CHARS: usize = 160;

/// A repository-derived string made safe to place on one line of a guide.
///
/// A subsystem's `area` and `summary` come from directory names, and a
/// directory can be named anything a filesystem allows: newlines, a Markdown
/// heading, a fenced block. Written verbatim into `CLAUDE.md`, `AGENTS.md` and
/// the Cursor rule, that is a prompt-injection channel into every agent that
/// loads the file. So the text is reduced to one line: control, bidirectional,
/// zero-width and line-separator characters become spaces and runs of
/// whitespace collapse; a backtick (which would end the code span the name
/// sits in) and `<`/`>` (HTML, and the `<?claude` block syntax) become
/// look-alike punctuation; leading `#`, `>`, `-`, `*`, `+` and `=` that
/// would make a Markdown block of it are dropped; and the length is capped.
fn inline_text(raw: &str) -> String {
    let mut out = String::with_capacity(raw.len().min(MAX_INLINE_CHARS * 4));
    let mut pending_space = false;
    let mut chars = 0;
    for c in raw.chars() {
        let c = match c {
            '`' => '\'',
            '<' => '\u{2039}',
            '>' => '\u{203a}',
            c if c.is_control()
                || c.is_whitespace()
                || matches!(
                    c,
                    '\u{061c}'
                        | '\u{200b}'..='\u{200f}'
                        | '\u{2028}'..='\u{202e}'
                        | '\u{2060}'..='\u{2069}'
                        | '\u{feff}'
                ) =>
            {
                pending_space = !out.is_empty();
                continue;
            }
            c => c,
        };
        if out.is_empty() && matches!(c, '#' | '>' | '-' | '*' | '+' | '=' | '\u{203a}') {
            continue;
        }
        if chars >= MAX_INLINE_CHARS {
            out.push('\u{2026}');
            break;
        }
        if pending_space {
            out.push(' ');
            chars += 1;
            pending_space = false;
        }
        out.push(c);
        chars += 1;
    }
    out
}

/// The "important surfaces" list: the first few subsystems, else the important
/// files, else an honest pointer at the artifact itself.
fn important_surfaces(map: &Value, map_rel: &str) -> Vec<String> {
    let mut lines: Vec<String> = subsystems(map)
        .take(6)
        .enumerate()
        .filter_map(|(index, sub)| {
            let area = inline_text(sub.get("area").and_then(Value::as_str)?);
            let summary = inline_text(sub.get("summary").and_then(Value::as_str).unwrap_or(""));
            Some(if summary.is_empty() {
                format!("{}. `{area}/`", index + 1)
            } else {
                format!("{}. `{area}/` — {summary}", index + 1)
            })
        })
        .collect();

    if lines.is_empty() {
        lines = map
            .get("important_files")
            .and_then(Value::as_array)
            .map(|files| files.as_slice())
            .unwrap_or(&[])
            .iter()
            .take(6)
            .filter_map(Value::as_str)
            .enumerate()
            .map(|(index, path)| format!("{}. `{}`", index + 1, inline_text(path)))
            .collect();
    }

    if lines.is_empty() {
        lines.push(format!("1. See `{map_rel}` for the file index."));
    }
    lines
}

/// What GitPulse Insights answers that the code graph cannot: who else is in
/// this repository right now.
///
/// DevMap describes the code. It has nothing to say about the other worktrees,
/// the live agent sessions, or the file two of them are both holding. An agent
/// that navigates the graph perfectly and then edits a file a sibling lane owns
/// has still collided. The two tools are named together because neither one's
/// answer is complete on its own.
///
/// The `ok` warning is the same honesty rule the rest of the kernel follows:
/// GitPulse's facets fail independently, so a facet that could not scan must
/// never be read as a facet that scanned and found nothing.
pub const GITPULSE_STEP: &str = "Before you change anything, ask GitPulse Insights what else is \
live in this repository. `gitpulse_insights` names the other worktrees, the running agent \
sessions, uncommitted work, contended files and index health in one call. Then \
`gitpulse_collision_risk` before touching a file another worktree may hold, \
`gitpulse_active_changes` for what is in flight, `gitpulse_change_context` / \
`gitpulse_provenance` for what changed and why, and `gitpulse_ledger_events` for the recorded \
history. Its facets fail independently — check each `ok`, because a facet that could not scan \
is not a facet that came back clean.";

/// Why the guide addresses agents it will never be loaded by.
///
/// A subagent gets the prompt its parent wrote, not this file. So the rule that
/// actually propagates is the one telling the parent to carry it forward; left
/// out, the guide binds exactly one agent and every lane it spawns starts by
/// grepping.
pub const DELEGATION_RULE: &str = "This binds every agent working here, not only the one reading \
this file. When you delegate — a subagent, a worktree lane, a handoff plan — name DevMap and \
GitPulse Insights in the prompt with the same precedence, rather than leaving that agent to grep \
its way in. When either tool cannot answer (truncated, `walk_incomplete`, empty on a built index, \
or a capability it does not have), record the gap and say so; do not silently fall back to grep \
and report the result as if the graph had confirmed it.";

/// Render the guide for `map`, whose artifact sits at `map_rel` relative to the
/// repository root.
pub fn agent_guide_text(map: &Value, map_rel: &str, graph_rel: &str, store_rel: &str) -> String {
    format!(
        "{AGENT_GUIDE_MARKER}\n\n{}",
        agent_guide_body(map, map_rel, graph_rel, store_rel)
    )
}

