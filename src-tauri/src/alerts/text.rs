//! The one place text from a program or a peer is made fit to show.
//!
//! What reaches the notification path is attacker-adjacent by construction:
//! any program the user runs can write an OSC body, and any process on the
//! account can send a hook report. A banner is rendered by the OS, so the
//! characters that matter are the ones that change what a reader sees without
//! being visible themselves: controls (`Cc`), the format characters (`Cf`:
//! bidirectional overrides and isolates, zero-width characters, the byte-order
//! mark, the tag block) and private-use code points, which render as whatever
//! a font maps them to.
//!
//! Rust's standard library has no `Cf` or `Co` predicate, so the classes come
//! from `scripts/fixtures/hidden-codepoints.json`, generated by
//! `scripts/hidden-codepoints.mjs` from the `\p{Cf}`, `\p{Co}`, `\p{Cc}` and
//! `\s` classes. The renderer's `clean` (`sessionActivity.ts`) reads the same
//! file, so the two cleaners cannot drift, and a drift test regenerates it when
//! Node's Unicode data moves. [`sanitize`] (collapse to one bounded line, for
//! banners, announcements, menus and briefs) and [`printable`] (remove, for a
//! token shown in a hook's own error) both read it; nothing else in the crate
//! keeps a second copy. `scripts/fixtures/sanitize-cases.json` is the readable
//! table both sides are also tested against, row by row.

use std::sync::OnceLock;

/// Longest text handed to an OS banner, in characters.
pub(super) const MAX_TEXT_CHARS: usize = 240;

struct Classes {
    drop: Vec<(u32, u32)>,
    space: Vec<(u32, u32)>,
}

fn classes() -> &'static Classes {
    static CLASSES: OnceLock<Classes> = OnceLock::new();
    CLASSES.get_or_init(|| {
        let table: serde_json::Value = serde_json::from_str(include_str!(
            "../../../scripts/fixtures/hidden-codepoints.json"
        ))
        .expect("scripts/fixtures/hidden-codepoints.json is JSON");
        let ranges = |key: &str| -> Vec<(u32, u32)> {
            table[key]
                .as_array()
                .unwrap_or_else(|| panic!("hidden-codepoints.json has no {key} ranges"))
                .iter()
                .map(|range| {
                    let end = |at: usize| {
                        range[at]
                            .as_u64()
                            .and_then(|n| u32::try_from(n).ok())
                            .expect("a range bound is a code point")
                    };
                    (end(0), end(1))
                })
                .collect()
        };
        Classes {
            drop: ranges("drop"),
            space: ranges("space"),
        }
    })
}

/// Whether `ranges`, sorted and disjoint, holds `c`.
fn within(ranges: &[(u32, u32)], c: char) -> bool {
    let cp = c as u32;
    ranges
        .binary_search_by(|&(lo, hi)| {
            if cp < lo {
                std::cmp::Ordering::Greater
            } else if cp > hi {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

/// Whether `c` is a format character (`Cf`) or private use (`Co`): invisible
/// or reordering, and never text a reader asked to see.
///
/// Dropped without leaving a space, because a zero-width character between two
/// letters is not a word break.
pub fn is_hidden(c: char) -> bool {
    within(&classes().drop, c)
}

/// Whether `c` separates text: a control character (a newline starts a new
/// line, an escape starts a sequence) or whitespace of any kind, the line and
/// paragraph separators included.
fn is_separator(c: char) -> bool {
    within(&classes().space, c)
}

/// Collapses `text` to one bounded line a banner, menu or the renderer can
/// show: hidden characters dropped, separators turned into single spaces, the
/// whole cut at [`MAX_TEXT_CHARS`] with an ellipsis.
pub fn sanitize(text: &str) -> String {
    let mut out = String::with_capacity(text.len().min(512));
    let mut chars = 0usize;
    let mut space = false;
    for ch in text.chars() {
        if is_hidden(ch) {
            continue;
        }
        if is_separator(ch) {
            space = true;
            continue;
        }
        if space && chars > 0 {
            out.push(' ');
            chars += 1;
        }
        space = false;
        if chars >= MAX_TEXT_CHARS {
            out.push('…');
            break;
        }
        out.push(ch);
        chars += 1;
    }
    out
}

/// `text` with every hidden character and every separator removed, cut to
/// `max` characters: for a token printed inside a sentence of ours, where a
/// space would be as foreign as a newline.
pub fn printable(text: &str, max: usize) -> String {
    text.chars()
        .filter(|c| !is_hidden(*c) && !is_separator(*c))
        .take(max)
        .collect()
}
